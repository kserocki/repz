import type { SnapshotFile } from "../../db/seed/snapshot.schema.ts";
import { licenseUrl } from "./attribution.ts";

function enNameOf(exercise: SnapshotFile["exercises"][number]): string {
  return (
    exercise.translations.find((translation) => translation.locale === "en")?.name ?? exercise.id
  );
}

/**
 * Generated alongside `exercises.json` on every import (§3.7/§3.9): one credit per exercise plus
 * a header stating the compilation's own licence. CC BY-SA 4.0 is allowed to cover the whole
 * compilation even though individual rows are CC-BY-SA 3.0 or CC0 (CC BY-SA 3.0 §4(b)–(c) permits
 * relicensing an adaptation under a later version of the same license family; CC0 rows carry no
 * restriction at all) — never hand-edited, regenerated by every `pnpm import:wger`.
 */
export function renderAttributionMarkdown(snapshot: SnapshotFile): string {
  const header = [
    "# Exercise data attribution",
    "",
    "Exercise names, muscle groups, equipment and instructions in this catalog were sourced from " +
      "[wger.de](https://wger.de) and have been modified and translated by Repz. This compilation " +
      "is licensed under [CC BY-SA 4.0](https://creativecommons.org/licenses/by-sa/4.0/).",
    "",
    "| Exercise | Author | Original licence | Source | |",
    "|---|---|---|---|---|",
  ];

  const rows = snapshot.exercises.map((exercise) => {
    const name = enNameOf(exercise);
    const licenceLink = `[${exercise.license}](${licenseUrl(exercise.license)})`;
    const sourceLink = `[wger.de](${exercise.source.url})`;
    return `| ${name} | ${exercise.author} | ${licenceLink} | ${sourceLink} | modified |`;
  });

  return [...header, ...rows, ""].join("\n");
}
