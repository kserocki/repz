#!/usr/bin/env python3
"""Converts the exported Android app-icon SVGs into VectorDrawable XML.

Reads `brand/logo/app-icon/android-{background,foreground,monochrome}-108.svg`
(produced by `logo/src/variants.py`) and writes VectorDrawables to
`mobile/app/android/src/main/res/drawable/`. Stdlib only (`re`, `pathlib`):
unlike the SVG generators in this folder, this script needs no virtualenv.

Never edit the generated drawables by hand; change this script and re-run
it instead. Re-running it must leave `git status` clean.

Geometry: brand/LOGO.md §2. Colours: brand/LOGO.md §3.
"""
from __future__ import annotations

import re
from pathlib import Path

SRC_DIR = Path(__file__).resolve().parent
LOGO_DIR = SRC_DIR.parent
BRAND_DIR = LOGO_DIR.parent
REPO_ROOT = BRAND_DIR.parent
APP_ICON_DIR = LOGO_DIR / "app-icon"
DRAWABLE_DIR = REPO_ROOT / "mobile" / "app" / "android" / "src" / "main" / "res" / "drawable"

# The only solid fills the exported icon SVGs use, mapped to the Android colour
# resource (or framework colour) that carries the same value, so the generated
# drawables reference a token instead of repeating a literal hex (brand/LOGO.md §3).
FILL_TO_ANDROID_COLOR = {
    "#00C2E0": "@color/brand_cyan",
    "#0E1416": "@color/brand_ink",
    "#000000": "@android:color/black",
}

GROUP_RE = re.compile(
    r'<g transform="translate\(([-\d.]+)[ ,]+([-\d.]+)\)\s*scale\(([-\d.]+)(?:[ ,]+([-\d.]+))?\)">'
    r"(.*?)</g>",
    re.S,
)
PATH_RE = re.compile(r'<path id="([\w-]+)" fill="(#[0-9A-Fa-f]{6})" d="([^"]+)"/>')
RECT_RE = re.compile(r'<rect width="([\d.]+)" height="([\d.]+)" rx="([\d.]+)" fill="(#[0-9A-Fa-f]{6})"/>')

VIEWPORT_CENTER = 54.0  # half of the 108x108 viewport; the source symbol is already centred here.

# The SplashScreen API lays `windowSplashScreenAnimatedIcon` out in the 288 dp box it uses when
# there is no distinct icon background (a same-colour `windowSplashScreenIconBackgroundColor` does
# not switch it to the 240 dp box; measured in Coach's REP-11 round-1 review). The foreground/
# monochrome geometry occupies 60% of the 108-unit viewport, i.e. 172.8 dp in that 288 dp box, not
# the 144 dp the product decision calls for. Shrinking the splash-only copy by 5/6 (60% -> 50% of
# the viewport, scaled about VIEWPORT_CENTER so it stays centred) renders at 144 dp instead.
SPLASH_SYMBOL_SCALE = 5 / 6


def read_svg(name: str) -> str:
    return (APP_ICON_DIR / name).read_text()


def android_color(hex_value: str, source: str) -> str:
    try:
        return FILL_TO_ANDROID_COLOR[hex_value.upper()]
    except KeyError:
        raise SystemExit(
            f"{source}: unmapped fill colour {hex_value}. Add it to FILL_TO_ANDROID_COLOR, and if it "
            "is a new brand colour, to mobile/app/android/src/main/res/values/colors.xml as well."
        )


def rect_path_data(width: float, height: float, corner_radius: float) -> str:
    """A rect as pathData; handles the corner_radius = 0 case the background SVG uses."""
    if corner_radius <= 0:
        return f"M0,0 H{width:g} V{height:g} H0 Z"
    r = corner_radius
    return (
        f"M{r:g},0 H{width - r:g} A{r:g},{r:g} 0 0 1 {width:g},{r:g} "
        f"V{height - r:g} A{r:g},{r:g} 0 0 1 {width - r:g},{height:g} "
        f"H{r:g} A{r:g},{r:g} 0 0 1 0,{height - r:g} "
        f"V{r:g} A{r:g},{r:g} 0 0 1 {r:g},0 Z"
    )


def vector_xml(source: str, body: str) -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- Generated by brand/logo/src/android_vectors.py from brand/logo/app-icon/{source}. "
        "Do not edit by hand. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n'
        '    android:height="108dp"\n'
        '    android:viewportWidth="108"\n'
        '    android:viewportHeight="108">\n'
        f"{body}"
        "</vector>\n"
    )


def path_xml(indent: str, name: str, color: str, path_data: str) -> str:
    return (
        f"{indent}<path\n"
        f'{indent}    android:name="{name}"\n'
        f'{indent}    android:fillColor="{color}"\n'
        f'{indent}    android:pathData="{path_data}"/>\n'
    )


def background_drawable() -> str:
    source = "android-background-108.svg"
    width, height, corner_radius, fill = RECT_RE.search(read_svg(source)).groups()
    color = android_color(fill, source)
    body = path_xml(
        "    ", "background", color, rect_path_data(float(width), float(height), float(corner_radius))
    )
    return vector_xml(source, body)


def format_number(value: float, decimals: int) -> str:
    """Matches `variants.py`'s own formatting (`.2f` translate, `.4f` scale), so a group with no
    extra scale re-renders byte-identical to the source SVG's literal translate/scale text."""
    text = f"{value:.{decimals}f}"
    return text.rstrip("0").rstrip(".") if "." in text else text


def symbol_group(source: str, color_override: str | None, extra_scale: float = 1.0) -> str:
    translate_x, translate_y, scale_x, scale_y, inner = GROUP_RE.search(read_svg(source)).groups()
    translate_x = float(translate_x)
    translate_y = float(translate_y)
    scale_x = float(scale_x)
    scale_y = float(scale_y) if scale_y else scale_x

    if extra_scale != 1.0:
        translate_x = VIEWPORT_CENTER + (translate_x - VIEWPORT_CENTER) * extra_scale
        translate_y = VIEWPORT_CENTER + (translate_y - VIEWPORT_CENTER) * extra_scale
        scale_x *= extra_scale
        scale_y *= extra_scale

    paths = "".join(
        path_xml("        ", path_id, color_override or android_color(fill, source), path_data)
        for path_id, fill, path_data in PATH_RE.findall(inner)
    )
    return (
        "    <group\n"
        f'        android:translateX="{format_number(translate_x, 2)}"\n'
        f'        android:translateY="{format_number(translate_y, 2)}"\n'
        f'        android:scaleX="{format_number(scale_x, 4)}"\n'
        f'        android:scaleY="{format_number(scale_y, 4)}">\n'
        f"{paths}"
        "    </group>\n"
    )


def foreground_drawable() -> str:
    source = "android-foreground-108.svg"
    return vector_xml(source, symbol_group(source, color_override=None))


def monochrome_drawable() -> str:
    source = "android-monochrome-108.svg"
    return vector_xml(source, symbol_group(source, color_override=None))


def splash_symbol_drawable() -> str:
    """Same geometry as the monochrome layer, scaled down by SPLASH_SYMBOL_SCALE so the SplashScreen
    API renders it at 144 dp (not 172.8 dp) in its 288 dp no-background icon box. The fill is the
    themed splash colour, not a brand hex."""
    source = "android-monochrome-108.svg"
    return vector_xml(
        source,
        symbol_group(source, color_override="@color/splash_symbol", extra_scale=SPLASH_SYMBOL_SCALE),
    )


def write(name: str, content: str) -> None:
    DRAWABLE_DIR.mkdir(parents=True, exist_ok=True)
    (DRAWABLE_DIR / name).write_text(content)


def main() -> None:
    write("ic_launcher_background.xml", background_drawable())
    write("ic_launcher_foreground.xml", foreground_drawable())
    write("ic_launcher_monochrome.xml", monochrome_drawable())
    write("splash_symbol.xml", splash_symbol_drawable())


if __name__ == "__main__":
    main()
