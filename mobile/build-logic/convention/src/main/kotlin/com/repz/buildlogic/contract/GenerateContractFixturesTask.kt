package com.repz.buildlogic.contract

import org.gradle.api.DefaultTask
import org.gradle.api.Project
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import org.gradle.kotlin.dsl.register
import java.io.File

private const val MAX_FIXTURE_BYTES = 60_000

// <operationId>/request/<case>.json or <operationId>/<3-digit status>/<case>.json
private val OPERATION_FIXTURE_PATH = Regex("""^[a-zA-Z][a-zA-Z0-9]*/(request|\d{3})/[\w.-]+\.json$""")

// components/<SchemaName>/<case>.json
private val COMPONENT_FIXTURE_PATH = Regex("""^components/[A-Za-z][A-Za-z0-9]*/[\w.-]+\.json$""")

/** One JSON file under the fixtures root: its path relative to that root (forward slashes), and its raw text. */
internal data class ContractFixtureFile(
    val path: String,
    val content: String,
)

/**
 * Turns every JSON file under `contract/fixtures`, recursively, into a Kotlin source listing them
 * as string literals, so Kotlin/Native simulator tests (which have no resource bundle) can decode
 * them without any file I/O. See [registerGenerateContractFixtures] for wiring this into a module.
 */
@CacheableTask
abstract class GenerateContractFixturesTask : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val fixturesDirectory: DirectoryProperty

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val fixtures = collectContractFixtures(fixturesDirectory.get().asFile)

        val outputDir = outputDirectory.get().asFile
        outputDir.deleteRecursively()
        val packageDirectory = File(outputDir, "com/repz/app/core/network/contract").apply { mkdirs() }
        File(packageDirectory, "GeneratedContractFixtures.kt").writeText(generatedContractFixturesSource(fixtures))
    }
}

/**
 * Registers [GenerateContractFixturesTask] reading `<repo>/contract/fixtures` (one level above the
 * `mobile/` Gradle root). The caller adds its output to `commonTest`'s Kotlin source set, e.g.
 * `kotlin.sourceSets.commonTest { kotlin.srcDir(registerGenerateContractFixtures()) }`.
 */
fun Project.registerGenerateContractFixtures() =
    tasks.register<GenerateContractFixturesTask>("generateContractFixtures") {
        fixturesDirectory.set(rootProject.layout.projectDirectory.dir("../contract/fixtures"))
        outputDirectory.set(layout.buildDirectory.dir("generated/contractFixtures"))
    }

/** Every `.json` file under [fixturesDirectory], validated and sorted by path (deterministic output). */
internal fun collectContractFixtures(fixturesDirectory: File): List<ContractFixtureFile> =
    fixturesDirectory
        .walkTopDown()
        .filter { it.isFile }
        .map { file ->
            val relativePath = file.relativeTo(fixturesDirectory).invariantSeparatorsPath
            validateFixtureLayout(relativePath)
            val content = file.readText()
            check(content.toByteArray(Charsets.UTF_8).size <= MAX_FIXTURE_BYTES) {
                "Contract fixture $relativePath is larger than $MAX_FIXTURE_BYTES UTF-8 bytes, " +
                    "too large for a single JVM string constant"
            }
            ContractFixtureFile(relativePath, content)
        }.sortedBy { it.path }
        .toList()

private fun validateFixtureLayout(relativePath: String) {
    check(relativePath.endsWith(".json")) { "Contract fixture \"$relativePath\" is not a .json file" }
    check(OPERATION_FIXTURE_PATH.matches(relativePath) || COMPONENT_FIXTURE_PATH.matches(relativePath)) {
        "Contract fixture \"$relativePath\" doesn't match a known layout: " +
            "<operationId>/request/<case>.json, <operationId>/<status>/<case>.json or components/<Schema>/<case>.json"
    }
}

/** The body of `GeneratedContractFixtures.kt`: a `List<ContractFixture>` (that type is hand-written in `commonTest`). */
internal fun generatedContractFixturesSource(fixtures: List<ContractFixtureFile>): String =
    buildString {
        appendLine("package com.repz.app.core.network.contract")
        appendLine()
        appendLine("// Generated by GenerateContractFixturesTask. Do not edit by hand.")
        appendLine("internal val generatedContractFixtures: List<ContractFixture> =")
        appendLine("    listOf(")
        fixtures.forEach { fixture ->
            append("        ContractFixture(path = \"")
            append(escapeKotlinStringLiteral(fixture.path))
            append("\", json = \"")
            append(escapeKotlinStringLiteral(fixture.content))
            appendLine("\"),")
        }
        appendLine("    )")
    }

/** Escapes [raw] for a Kotlin double-quoted string literal: `\`, `"`, `$`, and every control character. */
internal fun escapeKotlinStringLiteral(raw: String): String =
    buildString {
        raw.forEach { character ->
            when {
                character == '\\' -> append("\\\\")
                character == '"' -> append("\\\"")
                character == '$' -> append("\\$")
                character == '\n' -> append("\\n")
                character == '\r' -> append("\\r")
                character == '\t' -> append("\\t")
                character.code < 0x20 -> append("\\u%04x".format(character.code))
                else -> append(character)
            }
        }
    }
